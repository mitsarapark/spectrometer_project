#!/usr/bin/env python3
"""
Train a PLS regression on a spectrometer dataset and export a C header
that the ESP32 firmware can compile in.

Dataset format (written by the device at /dataset.csv):

    nm_0,nm_1,...,nm_{K-1},concentration
    i_0,i_1,...,i_{K-1},c
    ...

Usage:
    python train_plsr.py --csv dataset.csv --out ../spectrometer/model_weights.h
"""

import argparse
import datetime
import pathlib
import sys

import numpy as np
import pandas as pd
from sklearn.cross_decomposition import PLSRegression
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.model_selection import KFold, cross_val_predict
from sklearn.preprocessing import StandardScaler

try:
    from augment import augment_dataset
except ImportError:  # allow running from another directory
    sys.path.insert(0, str(pathlib.Path(__file__).parent))
    from augment import augment_dataset


def load_dataset(csv_path: pathlib.Path):
    df = pd.read_csv(csv_path)
    if df.shape[1] < 2:
        raise ValueError("dataset needs at least one wavelength column plus concentration")

    try:
        nm = np.array([float(c) for c in df.columns[:-1]], dtype=float)
    except ValueError:
        raise ValueError(
            "first CSV row must be the wavelength header produced by the device"
        )

    X = df.iloc[:, :-1].to_numpy(dtype=float)
    y = df.iloc[:, -1].to_numpy(dtype=float)

    if len(X) < 3:
        raise ValueError(f"need at least 3 samples, got {len(X)}")
    if np.isnan(X).any() or np.isnan(y).any():
        raise ValueError("dataset contains NaN values")

    return nm, X, y


def choose_components(X, y, max_components, seed):
    n_splits = min(5, len(X))
    cv = KFold(n_splits=n_splits, shuffle=True, random_state=seed)
    best_k, best_rmse = 1, float("inf")

    limit = max(1, min(max_components, X.shape[1], len(X) - 1))
    for k in range(1, limit + 1):
        model = PLSRegression(n_components=k, scale=False)
        pred = cross_val_predict(model, X, y, cv=cv)
        rmse = float(np.sqrt(mean_squared_error(y, pred.ravel())))
        print(f"  n_components={k:2d}  cv-RMSE={rmse:.4f}")
        if rmse < best_rmse:
            best_k, best_rmse = k, rmse

    return best_k, best_rmse


def flatten_model(model, scaler, X_mean, X_std, y_mean):
    """Collapse standardisation + PLS into y = B0 + sum(B[i] * x[i])."""
    coef = model.coef_.ravel()          # applies to standardised X
    B = coef / X_std
    B0 = float(y_mean - np.dot(B, X_mean))
    return B, B0


def export_header(path, *, nm, B, B0, rmse, r2, name, unit, n_samples, n_components):
    values = ", ".join(f"{v:.9g}f" for v in B)
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    text = f"""#ifndef MODEL_WEIGHTS_H
#define MODEL_WEIGHTS_H

/*
 * Generated by ml/train_plsr.py on {stamp}
 *   samples        : {n_samples}
 *   components     : {n_components}
 *   cv-RMSE        : {rmse:.4f}
 *   R2 (augmented) : {r2:.4f}
 *   wavelength span: {nm[0]:.1f} .. {nm[-1]:.1f} nm
 *
 * Do not edit by hand - rerun the training script instead.
 * Prediction: y = MODEL_B0 + sum(MODEL_B[i] * x[i]) where x is
 * spectrumCombined resampled to MODEL_INPUT_DIM points.
 */

#define MODEL_READY      {1}
#define MODEL_NAME       "{name}"
#define MODEL_UNIT       "{unit}"
#define MODEL_INPUT_DIM  {len(B)}
#define MODEL_NM_MIN     {nm[0]:.4f}f
#define MODEL_NM_MAX     {nm[-1]:.4f}f
#define MODEL_RMSE       {rmse:.4f}f
#define MODEL_TRAINED_AT "{stamp}"

static const float MODEL_B0 = {B0:.9g}f;
static const float MODEL_B[MODEL_INPUT_DIM] = {{ {values} }};

#endif // MODEL_WEIGHTS_H
"""
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", default="dataset.csv", help="dataset CSV from the device")
    parser.add_argument(
        "--out",
        default=str(pathlib.Path(__file__).parent.parent / "spectrometer" / "model_weights.h"),
        help="generated header path",
    )
    parser.add_argument("--name", default="plsr", help="model name embedded in the header")
    parser.add_argument("--unit", default="a.u.", help="concentration unit for the UI")
    parser.add_argument("--max-components", type=int, default=15)
    parser.add_argument("--no-augment", action="store_true")
    parser.add_argument("--augment-copies", type=int, default=5)
    parser.add_argument("--noise", type=float, default=0.01)
    parser.add_argument("--baseline", type=float, default=1.0)
    parser.add_argument("--scale", type=float, default=0.03)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    csv_path = pathlib.Path(args.csv)
    nm, X, y = load_dataset(csv_path)
    print(f"loaded {X.shape[0]} samples, {X.shape[1]} wavelengths "
          f"({nm[0]:.1f}-{nm[-1]:.1f} nm)")

    if not args.no_augment:
        X, y = augment_dataset(
            X, y,
            copies=args.augment_copies,
            noise=args.noise,
            baseline=args.baseline,
            scale=args.scale,
            seed=args.seed,
        )
        print(f"augmented to {X.shape[0]} samples")

    scaler = StandardScaler()
    Xs = scaler.fit_transform(X)

    print("searching n_components (cross-validated):")
    k, cv_rmse = choose_components(Xs, y, args.max_components, args.seed)
    print(f"selected n_components={k}, cv-RMSE={cv_rmse:.4f}")

    model = PLSRegression(n_components=k, scale=False)
    model.fit(Xs, y)

    pred = model.predict(Xs).ravel()
    r2 = r2_score(y, pred)

    B, B0 = flatten_model(model, scaler, scaler.mean_, scaler.scale_, float(y.mean()))
    export_header(
        pathlib.Path(args.out),
        nm=nm, B=B, B0=B0,
        rmse=cv_rmse, r2=r2,
        name=args.name, unit=args.unit,
        n_samples=len(y), n_components=k,
    )

    print(f"final R2 on {len(y)} samples: {r2:.4f}")
    if r2 < 0.7:
        print("WARNING: low R2 - collect more samples or refine the calibration.",
              file=sys.stderr)


if __name__ == "__main__":
    main()
